package com.pokeclip.chat.collector.broadcast;

/**
 * 붙이기 문{@link BroadcastSessions#start}과 판정기{@link BroadcastEventProcessor#process}의
 * 결과. <b>러너에게는 곧 「큐에서 지울지 말지」다</b> — {@code RETRY_LATER}만 큐에 남기고
 * 나머지는 지운다.
 *
 * <p>그래서 판정을 고를 때의 질문은 하나다: <b>이 편지를 다시 받아야 하는가.</b>
 * 다시 받아도 결과가 같을 것이면 지운다 — 안 지우면 FIFO라 같은 방송의 뒤 편지가 전부 막힌다.
 *
 * <p>🔴 <b>부르는 쪽이 둘이 되면서 물음이 하나 늘었다</b>(POK-219). 재부착에는 지울 편지가
 * 없고 대신 <b>「세션이 실제로 섰는가」</b>를 알아야 한다 — 안 서면 공백을 찍으면 안 된다.
 * 그 둘이 갈리는 자리가 {@link #LINK_REFUSED}다.
 */
public enum ProcessResult {

    /**
     * 처리했다. 다시 받을 필요가 없다.
     *
     * <p><b>붙이기 문이 이 값을 주면 그 방송의 세션이 서 있다</b> — 방금 열었거나 이미
     * 열려 있었거나 둘 중 하나다. 부르는 쪽은 이 값 하나로 「붙었다」를 판정해도 된다.
     */
    PROCESSED,

    /** 낡아서 무시했다. 다시 받아도 여전히 낡았다. */
    IGNORED_STALE,

    /**
     * 🔴 <b>auth가 열쇠를 영구히 거절했다 — 세션이 서 보지도 못했다.</b>
     * 다시 물어도 답이 같으므로 러너에게는 {@code PROCESSED}와 똑같이 「지운다」이지만,
     * <b>「붙었나」의 답은 정반대다.</b> 이 둘을 한 값으로 두면 재부착이 안 붙은 방송에
     * {@code gap_measured}를 찍는다(감사 라운드 3 H1, 주입으로 재현).
     *
     * <p><b>포기 메모는 이 값을 받는 쪽이 남긴다.</b> 문 안에서 남기면 재부착도 같은 문을
     * 쓰므로 <b>재부착이 자기 메모로 자기를 24시간 막는다</b> — 메모의 원래 목적이
     * 「편지를 지우기 전에 남긴다」인데 재부착에는 지울 편지가 없다(PRD 결정).
     */
    LINK_REFUSED,

    /** 지금은 못 했지만 다음에는 될 수 있다. <b>이 값만 편지를 큐에 남긴다.</b> */
    RETRY_LATER,

    /** 우리가 읽을 수 없는 편지다. 다시 받아도 못 읽는다. */
    UNREADABLE
}
