package com.pokeclip.chat.collector.broadcast;

/**
 * 편지가 가리키는 방송의 수집을 <b>실제로</b> 열고 닫는 자리 — 열쇠를 받아오고(태스크 7)
 * 세션 등록부를 여닫는다(태스크 9). 실물은 {@link LinkedSessionStarter}다.
 *
 * <p><b>이음매를 두는 이유</b>는 판정 규칙(끝난 방송인가 · 신원을 읽을 수 있는가 ·
 * 재전송을 거르지 않는가)이 세션·HTTP보다 먼저 굳어야 하고, 그것을 재려면 「붙이는 자리」가
 * 주입 가능해야 하기 때문이다. 그래서 판정기 검사는 진짜 DB를 쓰면서 세션은 안 연다.
 *
 * <p><b>여닫기가 한 이음매인 이유</b>: 편지 두 종류가 같은 것(그 방송의 수집)을 반대 방향으로
 * 움직인다. 인터페이스를 둘로 가르면 판정기가 같은 구현체를 두 이름으로 두 번 받게 되고,
 * 검사의 가짜도 둘이 된다 — 한쪽만 고쳐지면 「열기는 재는데 닫기는 안 재는」 상태가 된다.
 */
public interface BroadcastSessions {

    /**
     * 시작 편지 하나를 붙인다.
     *
     * @return <b>판정값을 그대로 돌려준다</b> — 열쇠를 못 받은 이유에 따라 편지를 지울지
     *         남길지가 갈리는데(연동 없음이면 지우고, auth 장애면 남긴다) 그 구분은
     *         이 안쪽에서만 알 수 있다
     */
    ProcessResult start(LifecycleEnvelope envelope, StreamerId streamer);

    /**
     * 그 방송의 수집을 멈춘다.
     *
     * @return 닫을 세션이 있었는가. <b>없어도 정상이다</b> — 종료 편지는 재전송으로 두 번
     *         오고, 우리가 뜨기 전에 시작한 방송은 애초에 연 적이 없다. 그래서 이 값으로
     *         편지의 운명을 가르지 않는다
     */
    boolean stop(String streamId);
}
