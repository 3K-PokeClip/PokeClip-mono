package com.pokeclip.clip.support;

/**
 * 시험 픽스처가 쓰는 신원 번호. <b>전부 숫자여야 한다</b> — 자격 판정이 회원 번호를
 * {@code Long.parseLong}으로 읽으므로, 비숫자 신원은 auth에 닿기도 전에 「볼 수 없다」로
 * 접힌다. 판정이 붙기 전에 픽스처를 먼저 맞춰 두면, 나중에 빨간불이 났을 때
 * <b>픽스처 실수와 판정 결함을 가를 수 있다.</b>
 *
 * <p>여기 있는 것은 <b>여러 클래스가 나눠 쓰는 값 하나뿐</b>이다. 구독자 번호는 클래스마다
 * 다른 사람이어야 하므로(통로 상한이 사람 단위라 겹치면 남의 시험이 자리를 먹는다)
 * 각 클래스가 자기 것을 정하고, 이 값과 안 겹치게 <b>네 자리</b>를 쓴다.
 */
public final class TestIds {

    /**
     * 방송 픽스처의 스트리머 번호. <b>한 곳에서만 정한다</b> — 스물여덟 곳에 흩어져 있던
     * 값이라 한 자리를 빠뜨리면 그 방송만 조용히 404가 되고, 그 하나를 찾는 데 드는 비용이
     * 여기 모으는 비용보다 크다(이 저장소에서 「같은 뿌리인데 한 자리만」이 여섯 번 났다).
     *
     * <p><b>문을 실제로 지나는 구독자 번호는 이 값과 달라야 한다</b> — 같으면 판정기가 auth에
     * 안 묻고 문자열만 비교하는 구현에서도 초록이 된다. 401에서 끊기는 갈래는 판정에 닿지
     * 않으므로 예외다.
     */
    public static final String STREAMER = "7";

    private TestIds() {
    }
}
