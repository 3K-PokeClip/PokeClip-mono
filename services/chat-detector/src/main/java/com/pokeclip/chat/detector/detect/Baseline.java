package com.pokeclip.chat.detector.detect;

import java.util.Arrays;

/**
 * "평소"를 낸다. <b>평균이 아니라 중앙값이다.</b>
 *
 * <p>연구노트 2절이 스케일에 따라 답을 갈랐다 — 긴 창(방송 전체)에서는 스파이크가 희소해
 * 평균이 강건하지만, <b>짧은 창(롤링 10~20분)에서는 창 안의 스파이크 비중이 커져 평균이
 * 부푼다.</b> 우리는 롤링을 쓰므로 중앙값이다.
 *
 * <p>부푼 기준선의 대가는 「연속 하이라이트를 놓치는 것」이다 — 방금 터진 것이 다음 판정의
 * 기준을 올려 버린다(연구노트 4절 「스파이크의 자기 오염」).
 *
 * <h2>🔴 「채팅이 있던 창」만 센다 — 조용했던 시간은 0으로 안 센다</h2>
 *
 * 집계는 채팅이 한 건도 없는 창에 줄을 안 만들고({@code GROUP BY}라 그렇다), 기준선 조회는
 * 표에 있는 줄만 읽는다. 그래서 「최근 15분의 모든 창」이 아니라 <b>「최근 15분 중 채팅이
 * 있던 창들」</b>의 중앙값이다.
 *
 * <p><b>사용자 결정이다</b>(계획 검증 F6이 차이를 재현해 물었다). 15분(창 180개) 중 다섯 창에만
 * 10건씩 있는 조용한 방송에서 기준선이 <b>10.0</b>이 된다 — 0으로 셌다면 0.0이다.
 * 20건짜리 창이 와도 배율 2.0이라 안 잡힌다.
 *
 * <p><b>덜 잡히는 쪽이 안전하다는 판단이다.</b> 가짜 카드가 섞이면 편집자가 하나씩 열어 보다가
 * 기능을 안 쓰게 되고, 놓친 하이라이트는 원래 하던 대로 찾으면 된다 — 손해가 대칭이 아니다.
 * 연구노트도 「소형 채널은 채팅 단독 탐지를 현재로선 신뢰 불가」로 이미 재려 뒀고,
 * ADR-011은 「신뢰도 미달 채널은 자동 탐지를 정직하게 비활성화」라고 적는다.
 * <b>조용한 방송에서 자동 탐지가 사실상 꺼지는 것이 의도와 같은 방향이다.</b>
 *
 * <p>워밍업도 같이 그렇게 읽힌다 — {@code warmupWindows}는 「시간 창 24개」가 아니라
 * <b>「채팅이 있었던 창 24개」</b>다.
 */
public final class Baseline {

    private Baseline() {
    }

    /** @throws IllegalArgumentException 값이 하나도 없으면. 워밍업이 이 상황을 먼저 막는다 */
    public static double median(int[] values) {
        if (values.length == 0) {
            throw new IllegalArgumentException("기준선을 낼 값이 없다");
        }
        // 복사한다 — 부른 쪽의 배열 순서를 바꾸면 그쪽이 쓰는 순서(최신순)가 깨진다.
        int[] sorted = values.clone();
        Arrays.sort(sorted);
        int mid = sorted.length / 2;
        return sorted.length % 2 == 1
                ? sorted[mid]
                : (sorted[mid - 1] + sorted[mid]) / 2.0;
    }
}
